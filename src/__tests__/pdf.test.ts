import { describe, test, expect, beforeAll } from "bun:test";
import { writeFileSync, mkdirSync } from "fs";
import { join } from "path";
import { generatePdfFromHtml } from "../lib/pdf-renderer.js";

const OUTPUT_DIR = join(process.cwd(), "output");
beforeAll(() => mkdirSync(OUTPUT_DIR, { recursive: true }));

describe("PDF Renderer (Playwright)", () => {
  test("generates PDF from minimal HTML", async () => {
    const html = `<!DOCTYPE html>
<html>
<head>
<style>
  body { font-family: sans-serif; padding: 40px; }
  h1 { color: #1a1a2e; border-bottom: 3px solid #3b82f6; padding-bottom: 8px; }
  p { color: #4a4a6a; line-height: 1.6; }
  table { width: 100%; border-collapse: collapse; margin: 20px 0; }
  th { background: #1a1a2e; color: white; padding: 10px; }
  td { padding: 8px 10px; border-bottom: 1px solid #e5e7eb; }
  tr:nth-child(even) td { background: #f8fafc; }
</style>
</head>
<body>
  <h1>Test Document</h1>
  <p>This is a test PDF generated by Playwright without any AI call.</p>
  <h2>Table Test</h2>
  <table>
    <tr><th>Name</th><th>Value</th></tr>
    <tr><td>Alpha</td><td>100</td></tr>
    <tr><td>Beta</td><td>200</td></tr>
  </table>
  <h2>List Test</h2>
  <ul>
    <li>First item</li>
    <li>Second item</li>
    <li>Third item</li>
  </ul>
</body>
</html>`;

    const buf = await generatePdfFromHtml(html);

    // Verify it is a real PDF
    const magic = buf.subarray(0, 5).toString("ascii");
    expect(magic).toBe("%PDF-");
    expect(buf.length).toBeGreaterThan(2000);

    // Save so the user can inspect it
    const outPath = join(OUTPUT_DIR, "test-pdf-minimal.pdf");
    writeFileSync(outPath, buf);
    console.log(`✓ PDF saved: ${outPath} (${Math.round(buf.length / 1024)}KB)`);
  }, 30_000);

  test("generates PDF with embedded base64 image", async () => {
    // A tiny 1x1 red PNG in base64
    const tinyPng =
      "data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mP8z8BQDwADhQGAWjR9awAAAABJRU5ErkJggg==";

    const html = `<!DOCTYPE html><html><body style="padding:40px">
        <h1 style="color:#1a1a2e">Image Test</h1>
        <img src="${tinyPng}" alt="tiny" style="width:50px;height:50px">
        <p style="color:#4a4a6a">PDF with embedded base64 image.</p>
      </body></html>`;

    const buf = await generatePdfFromHtml(html);
    expect(buf.subarray(0, 5).toString("ascii")).toBe("%PDF-");

    const outPath = join(OUTPUT_DIR, "test-pdf-image.pdf");
    writeFileSync(outPath, buf);
    console.log(`✓ PDF saved: ${outPath} (${Math.round(buf.length / 1024)}KB)`);
  }, 30_000);
});
